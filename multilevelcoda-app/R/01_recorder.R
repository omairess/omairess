# ============================================================================
# 01_recorder.R — THE step recorder (house rules 6 + 8)
#
# Every stage upserts one step by id: a plain-language description (pipeline
# log) and the R code that reproduces it (exported script). Upserting keeps
# the log and the script identical to what the app currently shows. Steps are
# emitted in STEP_ORDER, whatever order the user clicked in, and a stage that
# becomes stale (e.g. data re-imported) clears the steps downstream of it.
# ============================================================================

STEP_ORDER <- c("import", "diary", "composition", "describe", "ternary", "complr",
                "model", "substitution", "sub_plot")

new_recorder <- function() {
  steps <- shiny::reactiveVal(list())
  list(
    # reads are isolated so an observer that records never depends on the
    # recorder itself (that would re-trigger it forever)
    record = function(id, description, code) {
      cur <- shiny::isolate(steps())
      cur[[id]] <- list(id = id, description = description,
                        code = paste(code, collapse = "\n"),
                        time = Sys.time())
      steps(cur)
    },
    # drop this step and every step after it in STEP_ORDER
    clear_from = function(id) {
      cur <- shiny::isolate(steps())
      after <- STEP_ORDER[seq(match(id, STEP_ORDER), length(STEP_ORDER))]
      cur[intersect(names(cur), after)] <- NULL
      steps(cur)
    },
    steps = steps
  )
}

ordered_steps <- function(steps_list) {
  steps_list[intersect(STEP_ORDER, names(steps_list))]
}

# Standalone script: header with versions, library() calls, the helper
# functions verbatim (so no app file is needed), then every recorded step.
build_script <- function(steps_list, helpers_path, pkgs = SCRIPT_PACKAGES) {
  vers <- pkg_versions(pkgs)
  header <- c(
    "# =====================================================================",
    "# Reproducible multilevelcoda analysis \u2014 generated by the CoDA diary app",
    paste0("# Generated: ", format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")),
    paste0("# ", R.version.string),
    "# Package versions at generation time:",
    paste0("#   ", format(names(vers), width = 15), vers),
    "#",
    "# Put the data files next to this script (or change data_dir), then",
    "# source() it in a fresh R session. Stan needs a C++ toolchain",
    "# (macOS: xcode-select --install).",
    "# =====================================================================",
    "",
    paste0("suppressPackageStartupMessages(library(", pkgs, "))"),
    "",
    "# ---- helper functions (identical to the app's R/02_diary_helpers.R) ----",
    readLines(helpers_path, warn = FALSE, encoding = "UTF-8"),
    "# ---- end of helper functions ------------------------------------------",
    ""
  )
  st <- ordered_steps(steps_list)
  body <- unlist(lapply(seq_along(st), function(i) {
    s <- st[[i]]
    c(sprintf("## Step %d: %s", i, s$description), s$code, "")
  }), use.names = FALSE)
  paste(c(header, body), collapse = "\n")
}

build_pipeline_log <- function(steps_list) {
  st <- ordered_steps(steps_list)
  if (!length(st)) return("No steps recorded yet.")
  lines <- vapply(seq_along(st), function(i) {
    s <- st[[i]]
    sprintf("%d. %s  [%s]", i, s$description, format(s$time, "%Y-%m-%d %H:%M:%S"))
  }, character(1))
  paste(c("Analysis pipeline", "=================", "", lines), collapse = "\n")
}

# R literal for a value, for baking app choices into the exported code.
r_lit <- function(x) {
  if (is.null(x)) return("NULL")
  if (is.character(x) && length(x) == 1) return(deparse(x))
  paste(deparse(x, width.cutoff = 500L), collapse = " ")
}
